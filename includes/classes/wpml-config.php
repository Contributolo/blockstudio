<?php
/**
 * WPML configuration class.
 *
 * @package Blockstudio
 */

namespace Blockstudio;

use DOMDocument;
use DOMElement;
use DOMXPath;
use WP_Error;

/**
 * Generates the WPML language configuration for Blockstudio blocks.
 *
 * WPML translates the attributes of a custom block only when a wpml-config.xml
 * declares them. A block without an entry is left to WPML's automatic string
 * detection, which offers every string attribute for translation, including
 * select values, file names, and URLs. This class declares the text fields of
 * every registered Blockstudio block and declares blocks without text fields
 * with translate="0".
 *
 * Fields are read from the registered block definitions, after custom field
 * expansion, attribute filters, overrides, and matching extensions. Keys follow
 * the storage rules of the attribute builder: Blockstudio stores every value
 * under blockstudio.attributes, fields in a group with an ID are prefixed with
 * that ID, groups without an ID and tabs add no level, and repeater rows are
 * matched with "*".
 *
 * Nothing here runs on a regular request: the configuration is generated on
 * demand by `wp bs wpml config`.
 *
 * @since 7.7.3
 */
final class Wpml_Config {

	/**
	 * Comment that opens the generated section in a wpml-config.xml file.
	 *
	 * @var string
	 */
	public const START = '<!-- blockstudio:start -->';

	/**
	 * Comment that closes the generated section in a wpml-config.xml file.
	 *
	 * @var string
	 */
	public const END = '<!-- blockstudio:end -->';

	/**
	 * Explanation written below the start marker.
	 *
	 * @var string
	 */
	private const NOTE = '<!-- Generated by wp bs wpml config. Run it again after changing block fields; edits between the markers are replaced. -->';

	/**
	 * Field types whose value is text an editor writes.
	 *
	 * @var array<int, string>
	 */
	private const TEXT_TYPES = array( 'text', 'textarea', 'richtext', 'wysiwyg' );

	/**
	 * Built-in field types whose value is not text to translate.
	 *
	 * WPML copies these values into the translation unchanged.
	 *
	 * @var array<int, string>
	 */
	private const VALUE_TYPES = array(
		'attributes',
		'block',
		'checkbox',
		'classes',
		'code',
		'color',
		'date',
		'datetime',
		'files',
		'gradient',
		'html-tag',
		'icon',
		'message',
		'number',
		'radio',
		'range',
		'select',
		'toggle',
		'token',
		'unit',
	);

	/**
	 * Collect the fields of every registered Blockstudio block.
	 *
	 * Fields that extensions add to a Blockstudio block are stored in the same
	 * attributes object, so they are included. Extensions of core or
	 * third-party blocks are not: an entry for those blocks would compete with
	 * the configuration that WPML or the block's plugin ships.
	 *
	 * @return array<string, array{title: string, fields: array}> Blocks by name, sorted by name.
	 */
	public static function registered_blocks(): array {
		$extensions = Build::extensions();
		$blocks     = array();

		foreach ( Build::blocks() as $name => $block ) {
			$name   = (string) $name;
			$fields = is_array( $block->blockstudio['attributes'] ?? null )
				? array_values( $block->blockstudio['attributes'] )
				: array();

			foreach ( Extensions::get_matches( $name, $extensions ) as $extension ) {
				if ( is_array( $extension->blockstudio['attributes'] ?? null ) ) {
					$fields = array_merge( $fields, array_values( $extension->blockstudio['attributes'] ) );
				}
			}

			$blocks[ $name ] = array(
				'title'  => is_string( $block->title ?? null ) ? $block->title : '',
				'fields' => $fields,
			);
		}

		ksort( $blocks, SORT_STRING );

		return $blocks;
	}

	/**
	 * Build the generated section of a wpml-config.xml file.
	 *
	 * The section starts with START and ends with END. Between them, every
	 * block gets one gutenberg-block element: translate="1" with a key for each
	 * text field, or translate="0" when it has none.
	 *
	 * Example:
	 *
	 *     $section = Wpml_Config::section( Wpml_Config::registered_blocks() );
	 *     echo Wpml_Config::document( $section['xml'] );
	 *
	 * @param array<string, array{title?: string, fields?: array}> $blocks Blocks by name, as returned by registered_blocks().
	 *
	 * @return array{xml: string, translated: int, untranslated: int, skipped: array<int, string>} The section for a
	 *         gutenberg-blocks element, the number of blocks with and without text fields, and the fields left out
	 *         because their type is unknown.
	 */
	public static function section( array $blocks ): array {
		$lines        = array( self::START, "\t\t" . self::NOTE );
		$skipped      = array();
		$translated   = 0;
		$untranslated = 0;

		foreach ( $blocks as $name => $block ) {
			$name   = (string) $name;
			$fields = is_array( $block['fields'] ?? null ) ? $block['fields'] : array();
			$keys   = self::unique( self::keys( $fields, '', array(), $name, $skipped ) );
			$type   = 'type="' . self::escape( $name ) . '"';

			if ( array() === $keys ) {
				++$untranslated;
				$lines[] = "\t\t<gutenberg-block {$type} translate=\"0\" />";
				continue;
			}

			++$translated;
			$title   = isset( $block['title'] ) && '' !== $block['title'] ? $block['title'] : $name;
			$lines[] = "\t\t<gutenberg-block {$type} translate=\"1\" label=\"" . self::escape( $title ) . '">';
			$lines   = array_merge(
				$lines,
				self::render(
					array(
						array(
							'name' => 'blockstudio',
							'keys' => array(
								array(
									'name' => 'attributes',
									'keys' => $keys,
								),
							),
						),
					),
					3
				)
			);
			$lines[] = "\t\t</gutenberg-block>";
		}

		$lines[] = "\t\t" . self::END;

		return array(
			'xml'          => implode( "\n", $lines ),
			'translated'   => $translated,
			'untranslated' => $untranslated,
			'skipped'      => $skipped,
		);
	}

	/**
	 * Wrap a generated section in a complete wpml-config.xml document.
	 *
	 * @param string $section Section from section().
	 *
	 * @return string The document, without a trailing newline.
	 */
	public static function document( string $section ): string {
		return implode(
			"\n",
			array(
				'<wpml-config>',
				"\t<gutenberg-blocks>",
				"\t\t" . $section,
				"\t</gutenberg-blocks>",
				'</wpml-config>',
			)
		);
	}

	/**
	 * Replace the generated section of an existing wpml-config.xml file.
	 *
	 * Only the text from START to END changes, so every other section and
	 * entry of the file stays byte for byte as it is.
	 *
	 * @param string $contents Current file contents.
	 * @param string $section  Section from section().
	 *
	 * @return string|WP_Error The new contents, or an error when the file does not contain each marker exactly once.
	 */
	public static function merge( string $contents, string $section ) {
		$start = strpos( $contents, self::START );
		$end   = strpos( $contents, self::END );

		if (
			false === $start ||
			false === $end ||
			$end < $start ||
			1 !== substr_count( $contents, self::START ) ||
			1 !== substr_count( $contents, self::END )
		) {
			return new WP_Error(
				'blockstudio_wpml_config_markers',
				sprintf(
					'The file has no Blockstudio section. Add the lines %1$s and %2$s once inside its gutenberg-blocks element, then run the command again.',
					self::START,
					self::END
				)
			);
		}

		return substr( $contents, 0, $start ) . $section . substr( $contents, $end + strlen( self::END ) );
	}

	/**
	 * Check the structure of a wpml-config.xml document.
	 *
	 * WPML accepts one gutenberg-blocks element directly inside wpml-config,
	 * and gutenberg-block elements only inside it.
	 *
	 * @param string $xml Document.
	 *
	 * @return array<int, string>|WP_Error Block types declared more than once, or an error when the document is not a valid configuration.
	 */
	public static function validate( string $xml ) {
		$document = new DOMDocument();
		$previous = libxml_use_internal_errors( true );
		$loaded   = $document->loadXML( $xml, LIBXML_NONET );
		libxml_clear_errors();
		libxml_use_internal_errors( $previous );

		// phpcs:ignore WordPress.NamingConventions.ValidVariableName.UsedPropertyNotSnakeCase -- DOM property.
		if ( ! $loaded || 'wpml-config' !== $document->documentElement?->nodeName ) {
			return new WP_Error( 'blockstudio_wpml_config_invalid', 'The result is not a well-formed wpml-config document.' );
		}

		$xpath    = new DOMXPath( $document );
		$sections = $xpath->query( '/wpml-config/gutenberg-blocks' );
		$entries  = $xpath->query( '/wpml-config/gutenberg-blocks/gutenberg-block' );
		$all      = $xpath->query( '//gutenberg-block' );

		if ( false === $sections || false === $entries || false === $all || 1 !== $sections->length || $entries->length !== $all->length ) {
			return new WP_Error( 'blockstudio_wpml_config_invalid', 'The markers must be inside the single gutenberg-blocks element of the file.' );
		}

		$counts = array();

		foreach ( $entries as $entry ) {
			if ( $entry instanceof DOMElement ) {
				$type            = $entry->getAttribute( 'type' );
				$counts[ $type ] = ( $counts[ $type ] ?? 0 ) + 1;
			}
		}

		return array_keys( array_filter( $counts, static fn( int $count ): bool => $count > 1 ) );
	}

	/**
	 * Build the key nodes for a list of fields.
	 *
	 * Keys follow the storage rules of Container_Field_Handler: a group with an
	 * ID prefixes the IDs of its fields, a group without an ID and tabs add no
	 * level, and repeater rows are one level matched with "*". Where the
	 * attribute builder stores nothing, for a group with an ID nested in another
	 * group, the key matches no value and WPML ignores it.
	 *
	 * @param array             $fields  Field definitions.
	 * @param string            $prefix  Storage key prefix from the enclosing groups with an ID.
	 * @param array<int,string> $parents Labels of the enclosing repeaters and groups with an ID.
	 * @param string            $block   Block name, for the skipped list.
	 * @param array<int,string> $skipped Fields of unknown types (passed by reference).
	 *
	 * @return array<int, array> Key nodes.
	 */
	private static function keys( array $fields, string $prefix, array $parents, string $block, array &$skipped ): array {
		$nodes = array();

		foreach ( $fields as $field ) {
			// Hidden fields hold values that editors do not write, such as block field references.
			if ( ! is_array( $field ) || ! empty( $field['hidden'] ) ) {
				continue;
			}

			$type  = is_string( $field['type'] ?? null ) ? $field['type'] : '';
			$id    = is_string( $field['id'] ?? null ) || is_int( $field['id'] ?? null ) ? (string) $field['id'] : '';
			$key   = '' === $prefix ? $id : $prefix . '_' . $id;
			$label = self::label( $field, $id );
			$inner = is_array( $field['attributes'] ?? null ) ? $field['attributes'] : array();

			if ( 'tabs' === $type ) {
				foreach ( is_array( $field['tabs'] ?? null ) ? $field['tabs'] : array() as $tab ) {
					$tab_fields = is_array( $tab['attributes'] ?? null ) ? $tab['attributes'] : array();
					$nodes      = array_merge( $nodes, self::keys( $tab_fields, $prefix, $parents, $block, $skipped ) );
				}
				continue;
			}

			if ( 'group' === $type ) {
				$nodes = '' === $id
					? array_merge( $nodes, self::keys( $inner, $prefix, $parents, $block, $skipped ) )
					: array_merge( $nodes, self::keys( $inner, $key, array_merge( $parents, array( $label ) ), $block, $skipped ) );
				continue;
			}

			if ( '' === $id || '' === $type ) {
				continue;
			}

			if ( 'repeater' === $type ) {
				$rows = self::unique( self::keys( $inner, '', array_merge( $parents, array( $label ) ), $block, $skipped ) );

				if ( array() !== $rows ) {
					$nodes[] = array(
						'name' => $key,
						'keys' => array(
							array(
								'name' => '*',
								'keys' => $rows,
							),
						),
					);
				}
				continue;
			}

			$path = implode( ': ', array_merge( $parents, array( $label ) ) );

			if ( in_array( $type, self::TEXT_TYPES, true ) ) {
				$nodes[] = array(
					'name'  => $key,
					'label' => $path,
				);
			} elseif ( 'link' === $type ) {
				// WPML points a URL declared as a link to the translated page when it saves a translation.
				$nodes[] = array(
					'name' => $key,
					'keys' => array(
						array(
							'name'  => 'title',
							'label' => $path,
						),
						array(
							'name'  => 'url',
							'type'  => 'link',
							'label' => $path . ': URL',
						),
					),
				);
			} elseif ( ! in_array( $type, self::VALUE_TYPES, true ) ) {
				$skipped[] = sprintf( '%1$s: %2$s (%3$s)', $block, $path, $type );
			}
		}

		return $nodes;
	}

	/**
	 * Keep the first node for each key name.
	 *
	 * @param array<int, array> $nodes Key nodes of one level.
	 *
	 * @return array<int, array> Key nodes with unique names.
	 */
	private static function unique( array $nodes ): array {
		$unique = array();

		foreach ( $nodes as $node ) {
			$unique[ $node['name'] ] ??= $node;
		}

		return array_values( $unique );
	}

	/**
	 * Render key nodes as indented XML lines.
	 *
	 * @param array<int, array> $nodes Key nodes.
	 * @param int               $depth Indentation depth in tabs.
	 *
	 * @return array<int, string> Lines.
	 */
	private static function render( array $nodes, int $depth ): array {
		$lines  = array();
		$indent = str_repeat( "\t", $depth );

		foreach ( $nodes as $node ) {
			$attributes = ' name="' . self::escape( $node['name'] ) . '"';

			foreach ( array( 'type', 'label' ) as $attribute ) {
				if ( isset( $node[ $attribute ] ) ) {
					$attributes .= ' ' . $attribute . '="' . self::escape( $node[ $attribute ] ) . '"';
				}
			}

			if ( empty( $node['keys'] ) ) {
				$lines[] = "{$indent}<key{$attributes} />";
				continue;
			}

			$lines[] = "{$indent}<key{$attributes}>";
			$lines   = array_merge( $lines, self::render( $node['keys'], $depth + 1 ) );
			$lines[] = "{$indent}</key>";
		}

		return $lines;
	}

	/**
	 * Get the label of a field for the translation editor.
	 *
	 * @param array  $field Field definition.
	 * @param string $id    Field ID, used when the field has no label.
	 *
	 * @return string Label.
	 */
	private static function label( array $field, string $id ): string {
		foreach ( array( 'label', 'title' ) as $property ) {
			if ( is_string( $field[ $property ] ?? null ) && '' !== trim( $field[ $property ] ) ) {
				return trim( $field[ $property ] );
			}
		}

		return $id;
	}

	/**
	 * Escape a value for an XML attribute.
	 *
	 * @param string $value Value.
	 *
	 * @return string Escaped value.
	 */
	private static function escape( string $value ): string {
		return htmlspecialchars( $value, ENT_QUOTES | ENT_XML1 | ENT_SUBSTITUTE, 'UTF-8' );
	}
}
