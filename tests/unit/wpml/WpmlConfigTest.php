	public function test_merge_replaces_only_the_marked_section(): void {
		$section  = $this->section(
			array(
				array(
					'id'   => 'heading',
					'type' => 'text',
				),
			)
		)['xml'];
		$before   = "<wpml-config>\n  <custom-types>\n    <custom-type translate=\"1\">book</custom-type>\n  </custom-types>\n  <gutenberg-blocks>\n    <gutenberg-block type=\"other/block\" translate=\"1\">\n      <key name=\"title\" />\n    </gutenberg-block>\n    ";
		$after    = "\n  </gutenberg-blocks>\n</wpml-config>\n";
		$contents = $before . Wpml_Config::START . "\n    <gutenberg-block type=\"acme/old\" translate=\"0\" />\n    " . Wpml_Config::END . $after;

		$merged = Wpml_Config::merge( $contents, $section );

		$this->assertSame( $before . $section . $after, $merged );
		$this->assertStringNotContainsString( 'acme/old', $merged );
		$this->assertSame( array(), Wpml_Config::validate( $merged ) );
		$this->assertSame( $merged, Wpml_Config::merge( $merged, $section ) );
	}

